#!/usr/bin/env python3
"""chance_methods.py -- every way of defining "chance", side by side.

Colocalization is always reported against a chance level, and the field's chance is
INDEPENDENCE: if tagging and activity were unrelated, P(activity+|tagged+) would equal
P(activity+). That is what `overlap_above_chance` computes.

Independence is violated in real tissue by things that are not biology. Measured on
M3 Hipp2 (2026-07-31):

  * SHARED PIXELS -- the activity marker is measured on the nucleus, so a tagged
    measure that also covers the nucleus is partly the same photons. Coupling scales
    with pixel overlap: nuclear 2.23x, whole-cell 1.34x, ring-only 1.10x, all measured
    among tagged-NEGATIVE cells where no biology can exist.
  * SPATIAL STRUCTURE -- tagged cells sit in neighbourhoods already richer in activity
    (14.7% vs 11.4% region-wide).
  * OVER-DETECTION -- spurious double-negative objects inflate N and deflate the
    baseline, inflating the ratio.

So control regions land at 1.5-2x rather than 1.0, and the honest question is not "is
this above 1" but "how far above the FLOOR is it". This module computes the same
quantity five ways so the floor is visible and the conclusion can be shown not to
depend on which definition is chosen.

  naive         P(act+|tag+) / P(act+)                  the field standard
  local         .. / activity among the k nearest NOT-tagged cells   [local_chance.py]
  fitted        .. / a model fitted on tagged-negatives  [expected_overlap.py]
  anchor_floor  the SAME statistic with a pseudo-marker built by thresholding the
                ANCHOR channel. The anchor has no biological relation to marker
                co-expression, so its ratio IS the technical floor -- measured, not
                modelled. Requires the `anchor_mean` export column.
  rotation      an empirical null: rotate the tagged cells' POSITIONS as a rigid body
                about the section centroid, re-assign tagged status to the nearest real
                cells, recompute. Preserves tagged-cell clustering, tissue shape and
                local density exactly; breaks only the alignment between channels.
                Assumption-free, and yields a p-value. **WEAK HERE, USE WITH CARE**:
                rotation randomises only the ANGULAR coordinate, so any confound with
                RADIAL structure survives it -- and brain sections are laminar and
                roughly concentric. Verified on synthetic data (2026-08-01): a purely
                spatial confound inflating the naive ratio to 2.08x still reads 1.34x
                after rotation. Treat it as a partial correction and a p-value, never
                as a clean null. `local` handles what rotation cannot.

NOTHING HERE DECIDES ANYTHING. Five numbers are printed next to each other so the
operator can compare them against what the image shows (CLAUDE.md: SEEN outranks any
computed baseline).

Usage:
    python3 chance_methods.py --project "<dir>" --regions CA1,CA3,STR
    python3 chance_methods.py --project "<dir>" --regions CA1 --plot out.png
    python3 chance_methods.py --self-test
"""

